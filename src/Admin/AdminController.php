<?php
/**
 * Admin Controller.
 *
 * Registers the "Price Lists" submenu under WooCommerce in the WordPress
 * admin menu and orchestrates the admin page rendering.
 *
 * Responsibilities:
 *   - Adds the submenu page via add_submenu_page().
 *   - Enqueues plugin CSS and JS only on this plugin's own admin page.
 *   - Renders the page wrapper (wrap div, H1, tab navigation).
 *   - Routes rendering to ImportPage or LogsPage based on the active tab.
 *   - Retrieves and clears the import result transient after a POST redirect.
 *
 * Tab routing:
 *   The admin page uses a single menu slug ("wcpl-import") with an internal
 *   tab system driven by the `?tab=` GET parameter. Valid tab values are
 *   "import" (default) and "logs".
 *
 * @package WCPL\Admin
 * @since   1.0.0
 */

namespace WCPL\Admin;

// Prevent direct access.
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Class AdminController
 */
class AdminController {

	/**
	 * WooCommerce parent menu slug (the menu item we attach under).
	 *
	 * @var string
	 */
	private const PARENT_SLUG = 'woocommerce';

	/**
	 * Our plugin's menu page slug.
	 *
	 * @var string
	 */
	public const PAGE_SLUG = 'wcpl-import';

	/**
	 * Azione nonce usata per tutti gli handler AJAX admin del plugin.
	 * Deve corrispondere al valore passato a wp_create_nonce() in enqueue_assets().
	 *
	 * @var string
	 */
	public const NONCE_ACTION = 'wcpl_admin_js';

	/**
	 * Hook suffix generated by WordPress for our submenu page.
	 * Format: {parent_slug}_page_{page_slug}
	 *
	 * @var string
	 */
	private const HOOK_SUFFIX = 'woocommerce_page_wcpl-import';

	/**
	 * Valid tab identifiers.
	 *
	 * @var string[]
	 */
	private const VALID_TABS = [ 'import', 'logs', 'data', 'updates' ];

	// ---------------------------------------------------------------------------
	// Hooks
	// ---------------------------------------------------------------------------

	/**
	 * Register all WordPress hooks needed by this class.
	 *
	 * Called by Plugin::register_admin_hooks() on the admin_init path.
	 *
	 * @return void
	 */
	public function register_hooks(): void {
		add_action( 'admin_menu', [ $this, 'add_submenu_page' ] );
		add_action( 'admin_enqueue_scripts', [ $this, 'enqueue_assets' ] );
	}

	// ---------------------------------------------------------------------------
	// Menu
	// ---------------------------------------------------------------------------

	/**
	 * Register the "Price Lists" submenu page under the WooCommerce menu.
	 *
	 * Requires the `manage_woocommerce` capability so that only shop managers
	 * and admins can see and access the page.
	 *
	 * @return void
	 */
	public function add_submenu_page(): void {
		add_submenu_page(
			self::PARENT_SLUG,
			__( 'Price Lists', WCPL_TEXT_DOMAIN ),
			__( 'Price Lists', WCPL_TEXT_DOMAIN ),
			'manage_woocommerce',
			self::PAGE_SLUG,
			[ $this, 'render_page' ]
		);
	}

	// ---------------------------------------------------------------------------
	// Assets
	// ---------------------------------------------------------------------------

	/**
	 * Enqueue the plugin's admin CSS and JS.
	 *
	 * Only enqueues assets on this plugin's own admin page by checking the
	 * $hook parameter against our known hook suffix. This prevents loading
	 * our assets on every admin page.
	 *
	 * @param string $hook The current admin page hook suffix.
	 * @return void
	 */
	public function enqueue_assets( string $hook ): void {
		if ( self::HOOK_SUFFIX !== $hook ) {
			return;
		}

		// Admin stylesheet — minimal custom styles on top of WP's admin CSS.
		wp_enqueue_style(
			'wcpl-admin',
			WCPL_PLUGIN_URL . 'admin/css/wcpl-admin.css',
			[],
			WCPL_VERSION
		);

		// Admin JavaScript — source toggle, form submission UX.
		wp_enqueue_script(
			'wcpl-admin',
			WCPL_PLUGIN_URL . 'admin/js/wcpl-admin.js',
			[ 'jquery' ],
			WCPL_VERSION,
			true // load in footer
		);

		// Pass PHP data to JavaScript via wp_localize_script().
		wp_localize_script(
			'wcpl-admin',
			'wcplAdmin',
			[
				'ajaxUrl'        => admin_url( 'admin-ajax.php' ),
				'nonce'          => wp_create_nonce( self::NONCE_ACTION ),
				'importing_text' => esc_html__( 'Importing, please wait…', WCPL_TEXT_DOMAIN ),
				'i18n'           => [
					// Tab Aggiornamenti.
					'checkingUpdate'  => esc_html__( 'Checking for updates…', WCPL_TEXT_DOMAIN ),
					'upToDate'        => esc_html__( 'The plugin is up to date.', WCPL_TEXT_DOMAIN ),
					/* translators: %s: numero versione più recente */
					'updateAvailable' => esc_html__( 'A new version is available: %s', WCPL_TEXT_DOMAIN ),
					'changelog'       => esc_html__( 'Changelog', WCPL_TEXT_DOMAIN ),
					'updateNow'       => esc_html__( 'Update now', WCPL_TEXT_DOMAIN ),
					'errorCheck'      => esc_html__( 'Unable to check for updates. Please try again.', WCPL_TEXT_DOMAIN ),
				],
			]
		);
	}

	// ---------------------------------------------------------------------------
	// Page Rendering
	// ---------------------------------------------------------------------------

	/**
	 * Render the full admin page.
	 *
	 * This is the callback passed to add_submenu_page(). It outputs the page
	 * wrapper, tab navigation, and delegates content rendering to ImportPage
	 * or LogsPage depending on the active tab.
	 *
	 * @return void
	 */
	public function render_page(): void {
		// Determine active tab (default: 'import').
		$current_tab = isset( $_GET['tab'] ) // phpcs:ignore WordPress.Security.NonceVerification.Recommended
			? sanitize_key( wp_unslash( $_GET['tab'] ) ) // phpcs:ignore WordPress.Security.NonceVerification.Recommended
			: 'import';

		if ( ! in_array( $current_tab, self::VALID_TABS, true ) ) {
			$current_tab = 'import';
		}

		// Retrieve import result transient (set after a POST redirect).
		$import_result = null;
		if ( isset( $_GET['imported'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended
			$transient_key = 'wcpl_import_result_' . get_current_user_id();
			$stored        = get_transient( $transient_key );
			if ( false !== $stored ) {
				$import_result = $stored;
				delete_transient( $transient_key );
			}
		}

		// ── Page wrapper start ─────────────────────────────────────────────────
		?>
		<div class="wrap wcpl-wrap">
			<h1 class="wp-heading-inline">
				<?php esc_html_e( 'Price Lists', WCPL_TEXT_DOMAIN ); ?>
			</h1>

			<?php $this->render_tab_nav( $current_tab ); ?>

			<div class="wcpl-tab-content">
				<?php
				if ( 'logs' === $current_tab ) {
					$logs_page = new LogsPage();
					$logs_page->render_content();
				} elseif ( 'data' === $current_tab ) {
					$data_page = new DataPage();
					$data_page->render_content();
				} elseif ( 'updates' === $current_tab ) {
					$updates_page = new UpdatesPage();
					$updates_page->render_content();
				} else {
					$import_page = new ImportPage();
					$import_page->render_content( $import_result ?? [] );
				}
				?>
			</div>
		</div>
		<?php
	}

	// ---------------------------------------------------------------------------
	// Helpers
	// ---------------------------------------------------------------------------

	/**
	 * Render the tab navigation bar.
	 *
	 * Outputs a <nav> element with WordPress's standard .nav-tab-wrapper
	 * class so the tabs inherit the default WP admin tab styling.
	 *
	 * @param string $current_tab The currently active tab key.
	 * @return void
	 */
	private function render_tab_nav( string $current_tab ): void {
		$tabs = [
			'import'  => __( 'Import', WCPL_TEXT_DOMAIN ),
			'logs'    => __( 'Logs & History', WCPL_TEXT_DOMAIN ),
			'data'    => __( 'Data', WCPL_TEXT_DOMAIN ),
			'updates' => __( 'Updates', WCPL_TEXT_DOMAIN ),
		];
		?>
		<nav class="nav-tab-wrapper woo-nav-tab-wrapper">
			<?php foreach ( $tabs as $tab_key => $tab_label ) : ?>
				<a
					href="<?php echo esc_url( self::get_page_url( $tab_key ) ); ?>"
					class="nav-tab <?php echo $current_tab === $tab_key ? 'nav-tab-active' : ''; ?>"
				>
					<?php echo esc_html( $tab_label ); ?>
				</a>
			<?php endforeach; ?>
		</nav>
		<?php
	}

	/**
	 * Return the URL of the plugin's admin page, optionally with a tab.
	 *
	 * @param string $tab Tab key ('import' or 'logs'). Defaults to 'import'.
	 * @return string Absolute admin URL.
	 */
	public static function get_page_url( string $tab = 'import' ): string {
		return add_query_arg(
			[
				'page' => self::PAGE_SLUG,
				'tab'  => $tab,
			],
			admin_url( 'admin.php' )
		);
	}
}
